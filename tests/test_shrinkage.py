def need(path):
    if not path.exists():
        pytest.skip(f"local data cache missing: {path}")
    return path


@pytest.mark.slow
@pytest.mark.parametrize("branch", BRANCHES)
def test_estimation_population_counts(branch):
    need(sh.group_path())
    pop = sh.population(branch)
    assert len(pop) == POPULATION["rows"]
    assert pop.groupby("league").size().to_dict() == POPULATION["league"]
    assert pop.group.value_counts().to_dict() == POPULATION["group"]
    assert pop.groupby(["league", "group"]).size().to_dict() == POPULATION["cross"]


@pytest.mark.slow
@pytest.mark.parametrize("branch", BRANCHES)
def test_per_game_rows_reconcile_with_the_window_table(branch):
    pg = pd.read_parquet(need(sh.game_path(branch)))
    sh.reconcile(branch, pg)


@pytest.mark.slow
@pytest.mark.parametrize("branch", BRANCHES)
def test_dispersion_per_group(branch):
    pg = pd.read_parquet(need(sh.game_path(branch)))
    phi = sh.phi_table(sh.player_stats(pg, sh.population(branch)))
    got = {g: tuple(phi.loc[g, f"phi_{c}"] for c in sh.COMPONENTS) for g in phi.index}
    assert got == PHI[branch]


@pytest.mark.slow
@pytest.mark.parametrize("branch", BRANCHES)
def test_fay_herriot_variance_and_coefficients(branch):
    need(sh.game_path(branch))
    pop, _, _, psi = sh.branch_inputs(branch)
    fits, _ = sh.fit_population(pop, psi)
    got = {
        (branch, g, variant): (f["tau2"], list(f["b"]))
        for variant in sh.VARIANTS
        for g, f in fits[variant].items()
        if f is not None
    }
    assert got == {k: (t, b) for k, (t, b) in FITS.items() if k[0] == branch}
